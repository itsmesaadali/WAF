"""Copy the WAF's signatures into the Chrome extension, and record expected results.

Run after changing signatures:  py scripts\\export-extension-rules.py
It writes browser-extension/rules.js (used by the extension) and
browser-extension/test/parity-cases.json, which the extension's tests use to prove the
JavaScript engine gives the same answers as the Python WAF.
"""
from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "waf-backend"))
sys.path.insert(0, str(ROOT / "tests" / "evaluation"))

from app.detection.engine import scan_value  # noqa: E402
from app.detection.signatures import ALL_RULES  # noqa: E402

import dataset  # noqa: E402

EXTENSION = ROOT / "browser-extension"

EXTRA_CASES = [
    "' OR '1'='1", "1 UNION SELECT username, password FROM users --", "<script>alert(1)</script>",
    "<img src=x onerror=alert(1)>", "javascript:alert(document.cookie)", "%2527%2520OR%25201%253D1%2520--",
    "1 UN/**/ION SEL/**/ECT 1,2", "&#60;img src=x onerror=alert(1)&#62;", "JyBPUiAnMSc9JzE=",
    "java\tscript:alert(1)", "＜ｓｃｒｉｐｔ＞alert(1)", "<scr​ipt>alert(1)</script>",
    "\\u003cscript\\u003ealert(1)", "%u003Cscript%u003E", "O'Brien", "Please select a size",
    "I <3 this shop", "Is 1=1 always true?", "delete from cart", "blue shirt", "hello+world",
    "100%25 cotton", "%E2%9C%93 done", "%ZZbad", "a&amp;b&lt;c", "&lt;svg onload=alert(1)&gt;",
    "%4A%79%42%50%55%69%41%6E%4D%53%63%39%4A%7A%45%3D", "JyBPUiAnMSc9JzE%3D", "aGVsbG8gd29ybGQgdGhpcyBpcyBmaW5l",
]


def main() -> None:
    rules = [
        {"id": r.id, "name": r.name, "attack": r.attack, "severity": r.severity,
         "pattern": r.pattern.pattern, "form": r.form}
        for r in ALL_RULES
    ]
    rules_js = (
        "// Generated by scripts/export-extension-rules.py from the WAF's signatures. Don't edit by hand.\n"
        f"globalThis.WAF_RULES = {json.dumps(rules, indent=1, ensure_ascii=True)};\n"
        "if (typeof module !== \"undefined\") module.exports = globalThis.WAF_RULES;\n"
    )
    (EXTENSION / "rules.js").write_text(rules_js, encoding="utf-8")

    values: list[str] = list(EXTRA_CASES)
    for group in (dataset.SQLI_VALUES, dataset.XSS_VALUES, dataset.EVASION_VALUES):
        values.extend(group)
    seen: set[str] = set()
    cases = []
    for value in values:
        if value in seen:
            continue
        seen.add(value)
        cases.append({"value": value, "rules": sorted(f.rule_id for f in scan_value(value, "test"))})
    (EXTENSION / "test").mkdir(exist_ok=True)
    (EXTENSION / "test" / "parity-cases.json").write_text(
        json.dumps(cases, indent=1, ensure_ascii=True), encoding="utf-8"
    )
    print(f"Wrote {len(rules)} rules and {len(cases)} parity cases")


if __name__ == "__main__":
    main()
